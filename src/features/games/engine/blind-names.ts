/** `count` distinct names, each an animal and an adjective. */
export function pickBlindNames(count: number): string[] {
  const adjectives = shuffle(ADJECTIVES);
  return shuffle(ANIMALS)
    .slice(0, count)
    .map((animal, index) => `${animal} ${adjectives[index]}`);
}
